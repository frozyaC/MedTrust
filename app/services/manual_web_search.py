def _public_https(url: str) -> bool:
    """Exclude local, private and non-HTTPS addresses from user-visible links."""
    try:
        parsed = urlparse(url)
        host = (parsed.hostname or "").lower().rstrip(".")
        if parsed.scheme != "https" or not host or parsed.username or parsed.password:
            return False
        if parsed.port not in (None, 443):
            return False
        if host == "localhost" or host.endswith((".localhost", ".local", ".internal")):
            return False
        try:
            return ipaddress.ip_address(host).is_global
        except ValueError:
            return "." in host and all(part for part in host.split("."))
    except ValueError:
        return False


def _patient_search_context(patient: dict | None) -> str:
    """Build a compact, de-identified patient context for answer analysis.

    Do not copy free-text anamnesis into prompts. Reuse only the clinical factors
    extracted for search, after removing redaction artifacts and identifier labels.
    """
    if not isinstance(patient, dict):
        return ""

    parts: list[str] = []
    age = patient.get("age")
    if age is not None:
        try:
            age_value = int(age)
            if 0 <= age_value <= 130:
                parts.append(f"возраст: {age_value} лет")
        except (TypeError, ValueError):
            pass

    sex = _privacy_safe_query(str(patient.get("sex") or "")).strip()[:80]
    if sex:
        parts.append(f"пол: {sex}")

    factors = _patient_search_factors(patient)
    if factors:
        parts.append("клинические факторы: " + "; ".join(factors[:5]))

    return "; ".join(parts)[:1200]


def _clean_clinical_text(value: str) -> str:
    """Remove anonymization placeholders and identifier labels from a fragment."""
    text = _privacy_safe_query(str(value or "")[:2000])
    # Remove the placeholders generated by _privacy_safe_query first. This leaves
    # neighboring clinical words intact even when the sanitizer removed punctuation.
    text = re.sub(
        r"(?i)\[(?:фио|phone|email|identifier|document|date_of_birth|date|скрыто|имя)\]",
        " ",
        text,
    )
    # Strip labels, not the remainder of the clause: e.g. "телефон [phone]Фибрилляция"
    # must become "Фибрилляция", not disappear with the diagnosis.
    text = re.sub(
        r"(?i)\b(?:пациент(?:ка)?|фио|имя|телефон|моб\.?\s*телефон|email|e-mail|"
        r"электронная\s+почта|почта|адрес)\b\s*[:：]?",
        " ",
        text,
    )
    # Defensive cleanup for raw identifiers in case a future sanitizer misses one.
    text = re.sub(r"(?i)\b[\w.+-]+@[\w.-]+\.[a-z]{2,}\b", " ", text)
    text = re.sub(r"(?<!\d)(?:\+?\d[\s().-]?){10,15}(?!\d)", " ", text)
    text = re.sub(r"\[(?:[^\]]{1,40})\]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip(" ,;:.-")


def _patient_search_query_context(patient: dict | None) -> str:
    """Build the minimal patient profile that may be sent to the search provider.

    Unlike the answer-analysis context, this deliberately excludes the free-text
    anamnesis. Only age/sex and short, de-identified clinical factors are retained.
    """
    if not isinstance(patient, dict):
        return ""

    parts: list[str] = []
    age = patient.get("age")
    if age is not None:
        try:
            age_value = int(age)
            if 0 <= age_value <= 130:
                parts.append(f"возраст: {age_value} лет")
        except (TypeError, ValueError):
            pass

    sex = _privacy_safe_query(str(patient.get("sex") or "")).strip()[:80]
    if sex:
        parts.append(f"пол: {sex}")

    factors = _patient_search_factors(patient)
    if factors:
        parts.append("клинические факторы: " + "; ".join(factors[:5]))
    return "; ".join(parts)[:600]


def _patient_search_factors(patient: dict | None) -> list[str]:
    """Extract short clinical search factors without sending full free-text anamnesis.

    Contraindications are explicit factors. For anamnesis, only fragments containing
    common clinical/medication cues are retained; identifiers and unrelated narrative
    are excluded by the shared privacy sanitizer and this conservative filter.
    """
    if not isinstance(patient, dict):
        return []

    factors: list[str] = []
    contraindications = patient.get("contraindications") or []
    if isinstance(contraindications, str):
        contraindications = [contraindications]
    if isinstance(contraindications, (list, tuple)):
        for raw in contraindications[:8]:
            value = _clean_clinical_text(str(raw or ""))
            if value:
                factors.append(value[:180])

    anamnesis = _clean_clinical_text(str(patient.get("anamnesis") or ""))
    if anamnesis:
        clinical_cue = re.compile(
            r"диагноз|анамнез|заболев|болезн|синдром|аллерг|принимает|прием|приём|"
            r"препарат|лекарств|терапи|антикоагулянт|варфарин|апиксабан|ривароксабан|"
            r"дабигатран|клопидогрел|инсулин|диабет|гипертенз|гипотенз|аритми|"
            r"фибрилляц|инфаркт|инсульт|сердечн|почечн|печеночн|печёночн|беремен|"
            r"кормлен|иммунодефицит|иммуносупресс|asthma|diabetes|anticoag|warfarin|"
            r"apixaban|rivaroxaban|dabigatran|clopidogrel|allerg|kidney|renal|"
            r"hepatic|liver|pregnan|stroke|infarct|atrial fibrillation",
            re.IGNORECASE,
        )
        # Split into short clauses to avoid exporting an entire narrative to SearXNG.
        fragments = re.split(r"[\n.!?;]+|,\s+(?=[А-ЯЁA-Z])", anamnesis)
        for fragment in fragments:
            value = _clean_clinical_text(fragment)
            value = re.sub(r"(?i)\b(?:пациент(?:ка)?|телефон|email|e-mail|почта|адрес)\b", " ", value)
            value = re.sub(r"\s+", " ", value).strip(" ,;:-.")
            if not value:
                continue
            # A factor must contain clinical vocabulary and must not consist only
            # of residual contact/redaction labels after anonymization.
            if clinical_cue.search(value) and not re.fullmatch(
                r"(?i)(?:фио|phone|email|identifier|document|пациент|телефон)+", value
            ):
                factors.append(value[:180])

    # Stable de-duplication; do not include demographic attributes as clinical factors.
    unique: list[str] = []
    seen: set[str] = set()
    for factor in factors:
        key = re.sub(r"\W+", " ", factor.casefold().replace("ё", "е")).strip()
        if key and key not in seen:
            seen.add(key)
            unique.append(factor)
    return unique[:5]


def _patient_factor_terms(value: str) -> set[str]:
    """Return normalized content words used for conservative factor matching."""
    stop_words = {
        "прием", "приём", "принимает", "принимать", "имеет", "пациент", "пациентка",
        "анамнез", "диагноз", "состояние", "хронический", "хроническая", "хроническое",
        "который", "которая", "которые", "the", "with", "from", "patient", "history",
        "taking", "takes", "has", "have", "and", "for",
    }
    suffixes = (
        "иями", "ями", "ами", "ого", "ему", "ому", "ыми", "ими", "ого", "ему",
        "ов", "ев", "ей", "ый", "ий", "ая", "яя", "ое", "ее", "ые", "ие",
        "ых", "их", "ам", "ям", "ах", "ях", "ом", "ем", "ую", "юю", "а", "я",
        "ы", "и", "у", "ю", "е", "о",
    )
    result: set[str] = set()
    for token in re.findall(r"[a-zа-яё0-9]{4,}", unquote(value or "").casefold().replace("ё", "е")):
        if token in stop_words:
            continue
        stem = token
        for suffix in suffixes:
            if stem.endswith(suffix) and len(stem) - len(suffix) >= 4:
                stem = stem[:-len(suffix)]
                break
        if stem and stem not in stop_words:
            result.add(stem)
    return result


def _factor_english_terms(factor: str) -> list[str]:
    """Translate common clinical factors into compact English search terms.

    Topic translation is reused from web_search.py. Medication names/classes
    that are not represented in its topic taxonomy are covered separately.
    This is query expansion only, never a clinical equivalence or safety rule.
    """
    normalized = (factor or "").casefold().replace("ё", "е")
    terms: list[str] = []

    medication_patterns = (
        (r"варфарин|warfarin", "warfarin vitamin K antagonist anticoagulation management"),
        (r"апиксабан|apixaban", "apixaban direct oral anticoagulant management"),
        (r"ривароксабан|rivaroxaban", "rivaroxaban direct oral anticoagulant management"),
        (r"дабигатран|dabigatran", "dabigatran direct oral anticoagulant management"),
        (r"клопидогрел|clopidogrel", "clopidogrel antiplatelet therapy management"),
        (r"антикоагулянт|anticoagulant", "anticoagulant antithrombotic periprocedural management"),
        (r"антиагрегант|antiplatelet", "antiplatelet therapy periprocedural management"),
        (r"инсулин|insulin", "insulin diabetes periprocedural management"),
    )
    for pattern, english in medication_patterns:
        if re.search(pattern, normalized, re.IGNORECASE):
            terms.append(english)

    for topic in sorted(_topic_ids(factor)):
        english = _TOPIC_ENGLISH_TERMS.get(topic)
        if english:
            terms.append(english)

    # Stable de-duplication while preserving phrase order.
    output: list[str] = []
    seen: set[str] = set()
    for item in terms:
        key = item.casefold()
        if key not in seen:
            seen.add(key)
            output.append(item)
    return output[:3]


def _factor_alias_phrases(factor: str) -> list[str]:
    """Return Russian/English surface forms for cross-language source matching."""
    normalized = (factor or "").casefold().replace("ё", "е")
    aliases: list[str] = [factor]
    aliases_by_pattern = (
        (r"варфарин|warfarin", ("варфарин", "warfarin")),
        (r"фибрилляц.*предсерд|atrial\s+fibrillation", ("фибрилляция предсердий", "atrial fibrillation")),
        (r"апиксабан|apixaban", ("апиксабан", "apixaban")),
        (r"ривароксабан|rivaroxaban", ("ривароксабан", "rivaroxaban")),
        (r"дабигатран|dabigatran", ("дабигатран", "dabigatran")),
        (r"клопидогрел|clopidogrel", ("клопидогрел", "clopidogrel")),
        (r"антикоагулянт|anticoagulant", ("антикоагулянт", "anticoagulant", "anticoagulation")),
        (r"антиагрегант|antiplatelet", ("антиагрегант", "antiplatelet")),
    )
    for pattern, phrases in aliases_by_pattern:
        if re.search(pattern, normalized, re.IGNORECASE):
            aliases.extend(phrases)
    return list(dict.fromkeys(alias for alias in aliases if alias))


def _factor_matches_source(factor: str, result: WebSearchResult) -> bool:
    """Whether the title or available source text explicitly mentions a factor.

    URL tokens are intentionally excluded: a search phrase embedded in a URL is
    not evidence that the page body discusses the factor. Russian and English
    clinical terms are matched through explicit aliases, not loose translation.
    """
    source_text = f"{result.title or ''}\n{result.snippet or ''}"
    normalized_source = re.sub(r"[^a-zа-яё0-9]+", " ", unquote(source_text).casefold().replace("ё", "е")).strip()
    for alias in _factor_alias_phrases(factor):
        normalized_alias = re.sub(r"[^a-zа-яё0-9]+", " ", alias.casefold().replace("ё", "е")).strip()
        if normalized_alias and re.search(rf"(?<![a-zа-яё0-9]){re.escape(normalized_alias)}(?![a-zа-яё0-9])", normalized_source):
            return True

    factor_terms = _patient_factor_terms(factor)
    source_terms = _patient_factor_terms(source_text)
    if not factor_terms or not source_terms:
        return False
    matched = {
        factor_term
        for factor_term in factor_terms
        if any(
            source_term == factor_term
            or source_term.startswith(factor_term)
            or factor_term.startswith(source_term)
            for source_term in source_terms
        )
    }
    required = 2 if len(factor_terms) >= 3 else 1
    return len(matched) >= required


def _factor_english_query(question: str, factor: str) -> str:
    """Build an English query that keeps the requested procedure and patient factor."""
    question_topics = [
        _TOPIC_ENGLISH_TERMS[topic]
        for topic in sorted(_topic_ids(question))
        if topic in _TOPIC_ENGLISH_TERMS
    ]
    question_intents = [
        _INTENT_ENGLISH_TERMS[intent]
        for intent in sorted(_intent_ids(question))
        if intent in _INTENT_ENGLISH_TERMS
    ]
    factor_terms = _factor_english_terms(factor)
    components = [*question_topics[:3], *question_intents[:2], *factor_terms]
    if not factor_terms:
        return ""
    query = " ".join(dict.fromkeys(" ".join(components).split()))
    query += " clinical guideline periprocedural management"
    return query[:500]


def _factor_assessment_query(question: str, factor: str) -> str:
    """Build a scope-preserving query for checking factor-specific evidence.

    Do not carry routine preparation intents (e.g. fasting) into this check:
    evidence about anticoagulation around endoscopy is a different information
    need from fasting instructions, but must still concern the requested procedure.
    """
    topic_terms = [
        _TOPIC_ENGLISH_TERMS[topic]
        for topic in sorted(_topic_ids(question))
        if topic in _TOPIC_ENGLISH_TERMS
    ]
    factor_terms = _factor_english_terms(factor)
    if topic_terms and factor_terms:
        components = [*topic_terms[:3], *factor_terms]
        return " ".join(dict.fromkeys(" ".join(components).split())) + " clinical safety guidance"
    return f"{question} {factor} clinical safety guidance".strip()


def _queries(question: str, patient: dict | None = None) -> list[str]:
    cleaned = " ".join(question.split())[:350]
    patient_query_context = _patient_search_query_context(patient)
    patient_factors = _patient_search_factors(patient)

    def with_patient_context(value: str) -> str:
        value = " ".join(str(value or "").split())
        if not value:
            return ""
        if not patient_query_context:
            return value[:600]
        return f"{value}; контекст пациента: {patient_query_context}"[:600]

    # Preserve the patient-aware first pass and the exact question as a fallback.
    variants = [with_patient_context(cleaned), cleaned]

    # Search each clinically important factor in Russian and, where a known
    # clinical translation exists, English. The English form improves recall for
    # international guidelines while retaining the procedure/topic from the question.
    for factor in patient_factors[:3]:
        variants.append(f"{cleaned}; клинический фактор: {factor}"[:600])
        english_query = _factor_english_query(cleaned, factor)
        if english_query:
            variants.append(english_query)

    if re.search(r"(?:мрт|магнитно.?резонансн|\bmri\b)", cleaned, re.I):
        if re.search(r"контраст|contrast|gadolinium", cleaned, re.I):
            variants.extend(with_patient_context(item) for item in [
                "MRI contrast contraindications gadolinium patient safety kidney pregnancy",
                "MRI gadolinium contrast contraindications radiology patient information",
                "МРТ с контрастом противопоказания почки беременность",
            ])
        else:
            variants.append(with_patient_context("MRI contraindications patient safety"))

    variants.extend(with_patient_context(item) for item in _broad_search_queries(cleaned)[:3])
    simplified = re.sub(r"(?i)^(какие|какова|что такое|перечисли|расскажи|укажи)\s+", "", cleaned)
    simplified = simplified.rstrip("?.! ")
    variants.append(with_patient_context(simplified))
    return list(dict.fromkeys(x for x in variants if x))[:9]


def manual_web_answer(
    question: str, limit: int = 5, patient: dict | None = None,
) -> dict:
    client = SearXNGWebSearchClient()
    if not client.settings.web_search_enabled:
        return {
            "status": "disabled",
            "answer": "Веб-поиск отключён.",
            "sources": [],
            "warning": "Веб-поиск недоступен.",
        }

    safe_limit = max(1, min(8, int(limit)))
    patient_context = _patient_search_context(patient)
    patient_factors = _patient_search_factors(patient)
    search_queries = _queries(question, patient)
    cleaned_question = " ".join(question.split())[:350]

    # Keep the mapping between a focused query and the patient factor it was
    # designed to investigate. Query provenance is later used for pool-building
    # and diagnostics, not as proof that a result actually supports the factor.
    factor_query_indices: dict[int, str] = {}
    for factor in patient_factors[:3]:
        focused_queries = [f"{cleaned_question}; клинический фактор: {factor}"[:600]]
        english_query = _factor_english_query(cleaned_question, factor)
        if english_query:
            focused_queries.append(english_query)
        for focused_query in focused_queries:
            try:
                factor_query_indices[search_queries.index(focused_query) + 1] = factor
            except ValueError:
                continue

    attempts: list[dict] = []
    candidates: dict[str, WebSearchResult] = {}
    candidate_query_indices: dict[str, list[int]] = {}
    completed = False
    provider_count = 0
    blocked_count = 0

    # Execute the complete bounded query plan. A successful general query must
    # not prevent focused patient-factor queries from being attempted.
    for query_index, search_query in enumerate(search_queries, 1):
        timeout = (
            client.settings.web_search_timeout_seconds
            if query_index == 1
            else client.settings.web_search_fallback_timeout_seconds
        )
        raw = client._request(search_query, timeout)
        attempts.append({
            "query": search_query,
            "result_count": None if raw is None else len(raw),
        })
        if raw is None:
            continue
        completed = True
        provider_count += len(raw)
        for rank, entry in enumerate(raw, 1):
            if not isinstance(entry, dict):
                continue
            url = str(entry.get("url") or "").strip()
            if not _public_https(url):
                blocked_count += 1
                continue
            if url in candidates:
                query_indices = candidate_query_indices.setdefault(url, [])
                if query_index not in query_indices:
                    query_indices.append(query_index)
                continue
            host = urlparse(url).hostname or ""
            candidates[url] = WebSearchResult(
                title=str(entry.get("title") or host)[:300],
                url=url,
                snippet=str(
                    entry.get("content")
                    or entry.get("snippet")
                    or entry.get("description")
                    or ""
                )[:4000],
                rank=rank,
                domain=host,
            )
            candidate_query_indices[url] = [query_index]

    factor_query_indices_by_factor: dict[str, set[int]] = {}
    for query_index, factor in factor_query_indices.items():
        factor_query_indices_by_factor.setdefault(factor, set()).add(query_index)

    factor_query_candidate_counts: dict[str, int] = {}
    factor_candidate_preview: dict[str, list[dict[str, str | bool | list[int]]]] = {}
    for factor, query_indices in factor_query_indices_by_factor.items():
        factor_candidates = [
            (url, item)
            for url, item in candidates.items()
            if query_indices.intersection(candidate_query_indices.get(url, []))
        ]
        factor_candidates.sort(
            key=lambda pair: (
                int(_factor_matches_source(factor, pair[1])),
                len(query_indices.intersection(candidate_query_indices.get(pair[0], []))),
                -pair[1].rank,
            ),
            reverse=True,
        )
        factor_query_candidate_counts[factor] = len(factor_candidates)
        factor_candidate_preview[factor] = [
            {
                "title": item.title,
                "url": item.url,
                "domain": item.domain,
                "snippet": (item.snippet or "")[:600],
                "factor_mentioned_in_title_or_snippet": _factor_matches_source(factor, item),
                "returned_by_query_indices": candidate_query_indices.get(url, []),
                "also_returned_by_first_two_queries": bool(
                    set(candidate_query_indices.get(url, [])) & {1, 2}
                ),
            }
            for url, item in factor_candidates[:8]
        ]

    diagnostics = {
        "attempted_queries": attempts,
        "provider_results": provider_count,
        "rejected_unsafe_urls": blocked_count,
        "usable_results": len(candidates),
        "patient_context_applied": bool(patient_context),
        "patient_factor_query_count": len(factor_query_indices_by_factor),
        "patient_factor_query_variant_count": len(factor_query_indices),
        "patient_factor_query_candidate_counts": factor_query_candidate_counts,
        # Debug-only previews make it possible to distinguish query provenance
        # from actual factor mentions/evidence in the returned source text.
        "patient_factor_query_candidate_preview": factor_candidate_preview,
    }

    if not candidates:
        status = "api_error" if not completed else "no_results"
        detail = (
            "SearXNG не ответил ни на один поисковый запрос."
            if not completed
            else "SearXNG вернул 0 результатов."
            if provider_count == 0
            else "SearXNG вернул результаты, но ни один URL не прошёл проверку безопасности."
        )
        return {
            "status": status,
            "answer": detail,
            "sources": [],
            "warning": "Источники отсутствуют; генерировать фактический ответ не из чего.",
            "diagnostics": diagnostics,
        }

    def factor_relevance_matches(item: WebSearchResult) -> list[str]:
        """Factors mentioned by a source that is also relevant to this question."""
        matched: list[str] = []
        for factor in patient_factors:
            if not _factor_matches_source(factor, item):
                continue
            factor_query = _factor_assessment_query(question, factor)
            if is_relevant_web_result(factor_query, item):
                matched.append(factor)
        return matched

    def preliminary_score(item: WebSearchResult) -> tuple[int, int, int, int, int]:
        matched_factors = factor_relevance_matches(item)
        factor_evidence = any(
            has_answerable_web_evidence(_factor_assessment_query(question, factor), item)
            for factor in matched_factors
        )
        general_relevant = is_relevant_web_result(question, item)
        general_evidence = (
            general_relevant and has_answerable_web_evidence(question, item)
        )
        factor_query_hits = sum(
            1 for query_index in factor_query_indices
            if query_index in candidate_query_indices.get(item.url, [])
        )
        return (
            int(factor_evidence),
            len(matched_factors),
            int(general_evidence),
            int(general_relevant),
            factor_query_hits,
        )

    ordered_candidates = sorted(
        candidates.values(),
        key=lambda item: preliminary_score(item),
        reverse=True,
    )

    # Build the enrichment pool deliberately: retain good general results, but
    # also reserve room for candidates discovered by each focused patient query.
    # Without this, common preparation pages can crowd out all factor-specific
    # candidates before their full text is inspected.
    enrichment_cap = min(len(ordered_candidates), max(safe_limit * 4, 16))
    picked: list[WebSearchResult] = []
    picked_urls: set[str] = set()

    def add_to_pool(items: list[WebSearchResult], per_group_cap: int | None = None) -> None:
        added = 0
        for candidate in items:
            if candidate.url in picked_urls:
                continue
            if len(picked) >= enrichment_cap:
                return
            picked.append(candidate)
            picked_urls.add(candidate.url)
            added += 1
            if per_group_cap is not None and added >= per_group_cap:
                return

    for factor, query_indices in factor_query_indices_by_factor.items():
        factor_candidates = [
            item for item in candidates.values()
            if query_indices.intersection(candidate_query_indices.get(item.url, []))
        ]
        assessment_query = _factor_assessment_query(question, factor)
        factor_candidates.sort(
            key=lambda item: (
                int(_factor_matches_source(factor, item)),
                int(is_relevant_web_result(assessment_query, item)),
                int(
                    is_relevant_web_result(assessment_query, item)
                    and has_answerable_web_evidence(assessment_query, item)
                ),
                -int(item.rank),
            ),
            reverse=True,
        )
        add_to_pool(factor_candidates, per_group_cap=max(2, min(4, safe_limit)))
    # Keep a small guaranteed share for general-question sources, then fill remaining slots.
    add_to_pool(ordered_candidates, per_group_cap=max(2, safe_limit // 2))
    add_to_pool(ordered_candidates)

    trusted = [
        item for item in picked
        if client._parse_safe_results(
            [{"url": item.url, "title": item.title, "content": item.snippet}],
            limit=1,
        )
    ]
    trusted_urls = {item.url for item in trusted}
    enriched_by_url = {
        item.url: item
        for item in client._enrich_results(trusted, query=question)
    }

    assessed: list[dict] = []
    for original_item in picked:
        item = enriched_by_url.get(original_item.url, original_item)
        general_relevant = is_relevant_web_result(question, item)
        general_evidence = (
            general_relevant and has_answerable_web_evidence(question, item)
        )
        matched_factors = factor_relevance_matches(item)
        factor_evidence_matches = [
            factor for factor in matched_factors
            if has_answerable_web_evidence(_factor_assessment_query(question, factor), item)
        ]
        factor_evidence = bool(factor_evidence_matches)
        source_query_indices = candidate_query_indices.get(item.url, [])
        factor_query_matches = [
            factor for query_index, factor in factor_query_indices.items()
            if query_index in source_query_indices
        ]

        # Mentioning a patient factor is useful for discovery but is not treated
        # as evidence of a specific recommendation. General and factor evidence
        # remain separately exposed to the client.
        relevant = general_relevant or bool(matched_factors)
        evidence = general_evidence or factor_evidence
        relevance_score = (
            int(factor_evidence),
            len(factor_evidence_matches),
            len(matched_factors),
            int(general_evidence),
            int(general_relevant),
            len(factor_query_matches),
            -int(item.rank),
        )
        assessed.append({
            "item": item,
            "relevant": relevant,
            "evidence": evidence,
            "general_relevant": general_relevant,
            "general_evidence": general_evidence,
            "matched_factors": matched_factors,
            "factor_evidence": factor_evidence,
            "factor_evidence_matches": factor_evidence_matches,
            "factor_query_matches": factor_query_matches,
            "score": relevance_score,
        })

    assessed.sort(key=lambda entry: entry["score"], reverse=True)

    # Guarantee visibility for a clinically relevant source for each searched
    # factor, where one exists. A mention-only page is labelled unverified and
    # cannot be used as answer evidence; it is included for transparent review.
    selected: list[dict] = []
    selected_urls: set[str] = set()
    for factor in patient_factors[:3]:
        factor_candidates = [
            entry for entry in assessed
            if factor in entry["matched_factors"]
        ]
        for entry in factor_candidates:
            url = entry["item"].url
            if url not in selected_urls:
                selected.append(entry)
                selected_urls.add(url)
                break
        if len(selected) >= safe_limit:
            break

    for entry in assessed:
        if len(selected) >= safe_limit:
            break
        url = entry["item"].url
        if url not in selected_urls:
            selected.append(entry)
            selected_urls.add(url)

    sources: list[dict] = []
    context: list[str] = []
    matched_factor_set: set[str] = set()
    evidence_factor_set: set[str] = set()
    selected_factor_sources: dict[str, list[str]] = {factor: [] for factor in patient_factors}
    for index, entry in enumerate(selected, 1):
        item = entry["item"]
        sid = f"WEB{index}"
        matched = entry["matched_factors"]
        matched_factor_set.update(matched)
        evidence_factor_set.update(entry["factor_evidence_matches"])
        for factor in matched:
            selected_factor_sources.setdefault(factor, []).append(sid)
        sources.append({
            "source_id": sid,
            "title": item.title,
            "url": item.url,
            "domain": item.domain,
            "relevance": "relevant" if entry["relevant"] else "low",
            "evidence_status": "supported_candidate" if entry["evidence"] else "unverified",
            "content_type": "page" if item.url in trusted_urls else "search_snippet",
            "general_question_relevance": "relevant" if entry["general_relevant"] else "low",
            "general_question_evidence": bool(entry["general_evidence"]),
            "patient_factor_matches": matched,
            "patient_factor_evidence": bool(entry["factor_evidence"]),
            "patient_factor_evidence_matches": entry["factor_evidence_matches"],
            "patient_factor_search_matches": entry["factor_query_matches"],
            "patient_context_status": (
                "factor_evidence_supported" if entry["factor_evidence_matches"] else
                "factor_mentioned_only" if matched else
                "not_mentioned" if patient_factors else "not_applicable"
            ),
        })
        context.append(
            f"[{sid}] {item.title}\nURL: {item.url}\n"
            f"Общая релевантность вопросу: {'да' if entry['general_relevant'] else 'нет'}\n"
            f"Факторы пациента, упомянутые в тексте: {', '.join(matched) if matched else 'не обнаружены'}\n"
            f"Подтверждённые факторы пациента: {', '.join(entry['factor_evidence_matches']) if entry['factor_evidence_matches'] else 'не установлены'}\n"
            f"Текст: {item.snippet[:3500]}"
        )

    missing_factors = [factor for factor in patient_factors if factor not in matched_factor_set]
    mentioned_only_factors = matched_factor_set - evidence_factor_set
    diagnostics["patient_factors_searched"] = len(patient_factors)
    diagnostics["patient_factors_mentioned_in_selected_sources"] = len(matched_factor_set)
    diagnostics["patient_factors_with_evidence"] = len(evidence_factor_set)
    diagnostics["patient_factors_mentioned_only"] = len(mentioned_only_factors)
    diagnostics["patient_factors_not_found_in_selected_sources"] = len(missing_factors)
    diagnostics["patient_factor_mention_coverage"] = (
        round(len(matched_factor_set) / len(patient_factors), 3)
        if patient_factors else None
    )
    diagnostics["patient_factor_evidence_coverage"] = (
        round(len(evidence_factor_set) / len(patient_factors), 3)
        if patient_factors else None
    )
    diagnostics["patient_factor_coverage"] = diagnostics["patient_factor_evidence_coverage"]
    diagnostics["patient_factor_sources_selected"] = selected_factor_sources

    answer_context = [
        context[index]
        for index, entry in enumerate(selected)
        if entry["evidence"]
    ]
    if not answer_context:
        return {
            "status": "success",
            "answer": (
                "Поиск выполнен, но ни один из найденных источников не прошёл "
                "проверку релевантности и достаточности сведений для ответа. "
                "Индивидуальное влияние факторов пациента по найденным материалам не установлено."
            ),
            "sources": sources,
            "warning": (
                "Не используйте эти результаты как медицинское основание для решения. "
                "Нужны профильные источники с текстом, подтверждающим ответ."
            ),
            "diagnostics": diagnostics,
        }

    prompt = (
        "Ты помощник регистратора MedTrust. Это отдельный РУЧНОЙ веб-поиск, "
        "а не проверенный медицинский справочник. Ответь только по текстам ниже. "
        "Приводи только сведения, которые действительно содержатся в предоставленном тексте. "
        "Не выдумывай противопоказания, факты, цены, цитаты или URL. "
        "Разделяй общие рекомендации и сведения, относящиеся к факторам пациента. "
        "Упоминание фактора в источнике не означает, что источник подтверждает "
        "конкретную рекомендацию для такого пациента. Если фактор не найден в источниках, "
        "прямо укажи, что его влияние по найденным материалам не установлено. "
        "Не делай индивидуальных назначений и не советуй самостоятельно начинать, "
        "отменять или менять лекарства. Если данных мало, объясни, что установлено, "
        "а что не подтверждено. Каждый существенный факт снабжай ссылкой [WEB1], [WEB2] и т. п. "
        "Не добавляй предупреждение: система добавит его в конце.\n\n"
        f"Контекст пациента: {patient_context or 'не предоставлен'}. "
        "Учитывай его при оценке применимости найденных сведений, но не переноси "
        "общие выводы на пациента без прямого подтверждения источником.\n\n"
        f"Вопрос: {question}\n\n" + "\n\n".join(answer_context)
    )
    answer = str(get_gigachat_client().chat(prompt)).strip()
    if not answer:
        answer = "По найденным материалам не удалось сформировать содержательный ответ."
    links = "\n".join(
        f"- [{source['source_id']}] {source['title']} — {source['url']}"
        for source in sources
    )
    warning = (
        "Внимание: расширенный веб-поиск. Некоторые источники могут быть нерелевантными "
        "или содержать неподтверждённые сведения. Поисковые фрагменты не равнозначны "
        "проверенным медицинским рекомендациям. Перед записью пациента сверьте "
        "информацию с инструкциями клиники или профильным специалистом."
    )
    return {
        "status": "success",
        "answer": f"{answer}\n\nИсточники:\n{links}\n\n{warning}",
        "sources": sources,
        "warning": warning,
        "diagnostics": diagnostics,
    }
